import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { withPage } from './browser.mjs';

test('audio input picker: exact device, signal, permission failure, hotplug and remembered input', { timeout: 180000 }, async () => {
  await withPage(['--use-angle=swiftshader', '--enable-unsafe-swiftshader'], async ({ send, evaluate, until, errors, port }) => {
    await send('Page.addScriptToEvaluateOnNewDocument', { source: `
      window.__calls = []; window.__named = false;
      window.__devices = [{ kind: 'audioinput', deviceId: 'blackhole', label: 'BlackHole 2ch' }, { kind: 'audioinput', deviceId: 'mic', label: 'Built-in microphone' }, { kind: 'audiooutput', deviceId: 'speaker', label: 'Speakers' }];
      navigator.mediaDevices.enumerateDevices = async () => window.__devices.map(d => ({ ...d, label: window.__named ? d.label : '' }));
      navigator.permissions.query = async () => ({ state: localStorage.getItem('test.restore') ? 'granted' : 'prompt' });
      navigator.mediaDevices.getUserMedia = async constraints => {
        window.__calls.push(constraints);
        if (window.__deny) throw new DOMException('Permission denied', 'NotAllowedError');
        const id = constraints.audio.deviceId?.exact || 'mic';
        if (!window.__devices.some(d => d.deviceId === id)) throw new DOMException('Device missing', 'NotFoundError');
        const ctx = new AudioContext(), oscillator = ctx.createOscillator(), gain = ctx.createGain(), destination = ctx.createMediaStreamDestination();
        gain.gain.value = 0.1; oscillator.connect(gain).connect(destination); oscillator.start(); await ctx.resume();
        const track = destination.stream.getAudioTracks()[0];
        Object.defineProperty(track, 'label', { value: window.__devices.find(d => d.deviceId === id).label });
        window.__capture = { ctx, gain, track, destination }; window.__named = true;
        return destination.stream;
      };
    ` });
    const url = `http://127.0.0.1:${port}/?venue=studio&quality=low&webgl`;
    await send('Page.navigate', { url });
    await until('!!window.__show?.ready', 'The show did not start');
    await evaluate(`document.getElementById('audioSource').value = 'input'; document.getElementById('audioSource').dispatchEvent(new Event('change'));`);
    await until(`document.getElementById('audioInput').options.length === 3`, 'Inputs were not listed');
    assert.equal(await evaluate('window.__calls.length'), 0, 'listing devices must not request microphone permission');
    assert.equal(await evaluate(`document.getElementById('inputControls').hidden`), false);
    assert.deepEqual(await evaluate(`Array.from(document.getElementById('audioInput').options, o => o.textContent)`), ['System default', 'Audio input 1', 'Audio input 2']);
    await evaluate(`document.getElementById('audioInput').value = 'blackhole'; document.getElementById('audioInput').dispatchEvent(new Event('change')); document.getElementById('playFile').click();`);
    await until(`window.__show.audio.live && !document.getElementById('playFile').disabled && document.getElementById('status').dataset.audioState === 'receiving'`, 'The selected device did not receive audio');
    assert.equal(await evaluate(`window.__calls[0].audio.deviceId.exact`), 'blackhole');
    assert.equal(await evaluate(`window.__show.audio.label`), 'BlackHole 2ch');
    assert.equal(await evaluate(`document.getElementById('audioInput').selectedOptions[0].textContent`), 'BlackHole 2ch');
    assert.equal(await evaluate(`document.getElementById('inputLevel').value > 0`), true);
    await evaluate(`window.__show.audio.ctx.suspend()`);
    await until(`document.getElementById('status').dataset.audioState === 'suspended'`, 'Suspended audio was not explained');
    await evaluate(`window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Shift' }));`);
    await until(`document.getElementById('status').dataset.audioState === 'receiving'`, 'A key press did not resume suspended audio');
    await evaluate(`document.getElementById('sens').value = 2.5; window.__capture.gain.gain.value = 0;`);
    await until(`document.getElementById('status').dataset.audioState === 'silent'`, 'Silence was not detected');
    assert.equal(await evaluate(`document.getElementById('inputLevel').value`), 0, 'demo and sensitivity must not cause a false input signal');
    await evaluate(`window.__capture.gain.gain.value = 0.1;`);
    await until(`document.getElementById('status').dataset.audioState === 'receiving'`, 'Sound did not recover');
    await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false });
    fs.mkdirSync('rec/look', { recursive: true });
    const screenshot = await send('Page.captureScreenshot', { format: 'png' });
    fs.writeFileSync('rec/look/audio-input.png', Buffer.from(screenshot.data, 'base64'));
    await evaluate(`window.__previous = window.__show.audio.stream; window.__deny = true; document.getElementById('playFile').click();`);
    await until(`!document.getElementById('playFile').disabled && document.getElementById('status').textContent.includes('Audio permission denied')`, 'Permission denial was not explained');
    assert.equal(await evaluate(`window.__previous === window.__show.audio.stream && window.__capture.track.readyState === 'live'`), true, 'failed reconnect keeps the previous input running');
    await evaluate(`window.__deny = false; window.__devices = window.__devices.filter(d => d.deviceId !== 'blackhole'); navigator.mediaDevices.dispatchEvent(new Event('devicechange'));`);
    await until(`document.getElementById('inputHint').textContent.includes('unavailable')`, 'Device removal did not refresh the list');
    assert.equal(await evaluate(`document.getElementById('audioInput').value`), 'blackhole', 'an unavailable choice must not silently become the microphone');
    await evaluate(`document.getElementById('playFile').click();`);
    await until(`!document.getElementById('playFile').disabled && document.getElementById('status').textContent.includes('selected audio input is unavailable')`, 'Missing input was not explained');
    await evaluate(`window.__capture.track.stop();`);
    await until(`document.getElementById('status').dataset.audioState === 'lost'`, 'Disconnected input was not detected');
    await evaluate(`window.__devices.push({ kind: 'audioinput', deviceId: 'blackhole', label: 'BlackHole 2ch' }); navigator.mediaDevices.dispatchEvent(new Event('devicechange'));`);
    await until(`document.getElementById('audioInput').selectedOptions[0].textContent === 'BlackHole 2ch'`, 'Reattached input was not listed');
    await evaluate(`localStorage.setItem('test.restore', '1');`);
    await send('Page.navigate', { url });
    await until(`window.__show?.audio.live && document.getElementById('status').dataset.audioState === 'receiving'`, 'Remembered input was not restored');
    assert.equal(await evaluate(`window.__calls[0].audio.deviceId.exact`), 'blackhole');
    assert.equal(await evaluate(`document.getElementById('audioInput').value`), 'blackhole');
    await evaluate(`document.getElementById('audioSource').value = 'file'; document.getElementById('audioSource').dispatchEvent(new Event('change'));`);
    assert.equal(await evaluate(`document.getElementById('inputControls').hidden`), true);
    assert.equal(await evaluate(`(async () => {
      const audio = window.__show.audio, pending = [];
      navigator.mediaDevices.getUserMedia = () => new Promise(resolve => pending.push(resolve));
      const slow = audio.ctx.createMediaStreamDestination().stream, latest = audio.ctx.createMediaStreamDestination().stream;
      const first = audio.input('blackhole'), second = audio.input('mic');
      pending[1](latest); const connected = await second;
      pending[0](slow); const superseded = await first;
      return connected === true && superseded === false && audio.stream === latest && slow.getAudioTracks()[0].readyState === 'ended' && latest.getAudioTracks()[0].readyState === 'live';
    })()`), true, 'a slow older permission request must release its stream and leave the latest input connected');
    assert.deepEqual(errors, []);
  });
});
